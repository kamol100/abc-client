export type MenuIconName = keyof typeof MENU_ICONS;

export const MENU_ICON_NAMES = Object.keys(MENU_ICONS) as MenuIconName[];

export function isMenuIconName(value: unknown): value is MenuIconName {
  return typeof value === "string" && Object.prototype.hasOwnProperty.call(MENU_ICONS, value);
}

/** The stored icon when it is one we know, otherwise the item's own default. */
export function menuIcon(name: string | null | undefined, fallback: LucideIcon): LucideIcon {
  return isMenuIconName(name) ? MENU_ICONS[name] : fallback;
}
